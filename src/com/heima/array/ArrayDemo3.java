package com.heima.array;

public class ArrayDemo3 {
    public static void main(String[] args) {

        //数组的遍历

        //定义数组
        int[] arr = {10, 20, 30, 40, 50};

        //利用循环获取数组元素
        for (int i = 0; i < arr.length; i++) {
            System.out.println(arr[i]);
        }

        //快速生成：数组名.fori

    }
}
