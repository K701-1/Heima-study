package com.heima.loopfor;

public class ForDemo1 {
    public static void main(String[] args) {

        /*

        for(初始化语句；条件判断语句；条件控制语句){}

            初始化语句：开始条件
            条件判断语句：结束条件
            条件控制语句：进行的操作

        */

        //实现游戏中连续跳跃 10 次，用输出语句模拟跳跃逻辑

        for(int i = 1;i <= 10;i++){
            System.out.println("游戏人物在跳跃");
        }
    }
}
